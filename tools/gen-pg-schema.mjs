// Generates server/migrations/pg/0001_baseline.sql from the FINAL SQLite schema (SCHEMA + migrate() on an empty in-memory database).
// Usage: node tools/gen-pg-schema.mjs          (writes the file)       node tools/gen-pg-schema.mjs --check   (exit 1 if the file is out of date)
// The baseline is FROZEN once it ships: later schema changes get their own numbered file (0002_...sql) written by hand, next to the SQLite migrate() change.
import Database from 'better-sqlite3'; import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
import { SCHEMA, migrate } from '../server/core/schema.js';
const here = path.dirname(fileURLToPath(import.meta.url)); const OUT = path.join(here, '../server/migrations/pg/0001_baseline.sql');

export function sqliteFinalSchema() { const db = new Database(':memory:'); db.exec(SCHEMA); migrate(db); const rows = db.prepare("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid").all(); db.close(); return rows; }
const tableDdl = (sql) => sql
  .replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/\bTEXT NOT NULL UNIQUE COLLATE NOCASE\b/g, 'CITEXT NOT NULL UNIQUE')
  .replace(/\bINTEGER\b/g, 'BIGINT').replace(/\bREAL\b/g, 'DOUBLE PRECISION').replace(/\bBLOB\b/g, 'BYTEA');
export function generate() {
  const rows = sqliteFinalSchema(); const out = [];
  out.push('-- GENERATED by tools/gen-pg-schema.mjs from the SQLite schema (server/core/schema.js). DO NOT EDIT BY HAND. Frozen once shipped: add 0002_*.sql for later changes.',
    'CREATE EXTENSION IF NOT EXISTS citext SCHEMA public;', '',
    '-- the ledger is append-only: the same guarantee the SQLite triggers give',
    "CREATE OR REPLACE FUNCTION na_ledger_append_only() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'ledger is append-only'; END $$;", '');
  const triggers = [];
  for (const r of rows) {
    if (r.type === 'table') out.push(tableDdl(r.sql) + ';', '');
    else if (r.type === 'index') out.push(r.sql + ';');
    else if (r.type === 'trigger') { const m = /CREATE TRIGGER (\w+) BEFORE (UPDATE|DELETE) ON (\w+) BEGIN SELECT RAISE\(ABORT, 'ledger is append-only'\); END/.exec(r.sql); if (!m) throw new Error('unknown trigger shape, extend the generator: ' + r.sql); triggers.push(`CREATE TRIGGER ${m[1]} BEFORE ${m[2]} ON ${m[3]} FOR EACH ROW EXECUTE FUNCTION na_ledger_append_only();`); }
    else throw new Error('unhandled schema object: ' + r.type);
  }
  out.push('', ...triggers, '');
  return out.join('\n');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = generate();
  if (process.argv.includes('--check')) { const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''; if (cur !== text) { console.error('server/migrations/pg/0001_baseline.sql is out of date: run node tools/gen-pg-schema.mjs (but the baseline is frozen once shipped: add a 0002 file instead)'); process.exit(1); } console.log('baseline is current'); }
  else { fs.mkdirSync(path.dirname(OUT), { recursive: true }); fs.writeFileSync(OUT, text); console.log(`wrote ${OUT} (${text.split('\n').length} lines)`); }
}
